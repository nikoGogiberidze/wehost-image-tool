const { contextBridge, ipcRenderer, webUtils } = require('electron')

contextBridge.exposeInMainWorld('electronAPI', {
  // Resolve a dropped File object to its real disk path (files stay on disk,
  // never loaded into renderer memory)
  getPathForFile: (file) => webUtils.getPathForFile(file),

  // Image processing (payload carries file paths + output folder)
  processImages: (payload) => ipcRenderer.invoke('process:images', payload),
  onProgress: (callback) => {
    const handler = (_event, data) => callback(data)
    ipcRenderer.on('process:progress', handler)
    return () => ipcRenderer.removeListener('process:progress', handler)
  },

  // Thumbnails + previews (generated by Sharp in the main process)
  generateThumbnail: (filePath) => ipcRenderer.invoke('thumb:generate', { filePath }),
  generatePreview: (filePath, maxWidth) =>
    ipcRenderer.invoke('preview:generate', { filePath, maxWidth }),

  // Folder dialog
  saveFolder: () => ipcRenderer.invoke('dialog:saveFolder'),

  // Open a folder in the OS file explorer
  openFolder: (folderPath) => ipcRenderer.invoke('shell:openFolder', { folderPath }),

  // Settings store
  storeGet: (key) => ipcRenderer.invoke('store:get', { key }),
  storeSet: (key, value) => ipcRenderer.invoke('store:set', { key, value }),

  // Logo save
  saveLogo: (base64, originalPath) => ipcRenderer.invoke('logo:save', { base64, originalPath }),

  // Read saved logo as base64
  readLogo: () => ipcRenderer.invoke('logo:read')
})
